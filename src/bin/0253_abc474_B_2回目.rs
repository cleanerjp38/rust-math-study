use proconio::input;

fn main() {
    input! {
        n: usize,
        p: [u32; n],
    }

    for j in 0..n {
        let group = j / 10;

        if p[j] / 10 != group as u32 &&p[j] % 10 != 0 {
            println!("No");
            return;
        }
    }

    println!("Yes");
}
